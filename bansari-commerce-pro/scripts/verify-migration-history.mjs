#!/usr/bin/env node
/**
 * verify-migration-history.mjs
 * ----------------------------
 * Generates a READ-ONLY SQL report that answers, per migration, the only
 * question that matters before repairing migration history:
 *
 *   "Do the objects this migration creates actually exist in the database?"
 *
 * WHY THIS EXISTS
 *
 * `supabase migration list` shows 37 local migrations that the remote history
 * table has no record of — including ones whose features are demonstrably live
 * in production (Cashfree payments, coupons). They were applied by hand and
 * never recorded.
 *
 * The tempting fix is `supabase migration repair --status applied <all of
 * them>`. That is safe ONLY for migrations that genuinely ran. Marking an
 * unapplied migration as applied is unrecoverable in practice: `db push` will
 * skip it forever, and its tables/columns silently never get created.
 *
 * The other tempting fix — `supabase db push` — is the dangerous one. It would
 * replay all 37 against a live database holding real orders. This script
 * exists so neither has to be guessed at.
 *
 * WHAT IT DOES NOT DO
 *
 * It does not connect to the database, and it does not modify anything. It
 * reads local .sql files and prints a SELECT statement. Run that statement in
 * the Supabase SQL Editor; it only reads system catalogues.
 *
 * USAGE
 *   node scripts/verify-migration-history.mjs > /tmp/verify.sql
 *   # paste /tmp/verify.sql into Supabase → SQL Editor → Run
 */
import { readdirSync, readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const MIGRATIONS_DIR = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'supabase',
  'migrations'
);

/** Strip comments and string literals so they cannot produce false matches. */
function sanitise(sql) {
  return sql
    .replace(/--[^\n]*/g, ' ')
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .replace(/\$\$[\s\S]*?\$\$/g, ' $BODY$ ') // function bodies
    .replace(/'(?:[^']|'')*'/g, "''");
}

const qualify = (raw) => {
  const ident = raw.replace(/"/g, '').trim().toLowerCase();
  return ident.includes('.') ? ident : `public.${ident}`;
};

/**
 * Extract the objects a migration is expected to create.
 *
 * Deliberately conservative: only unambiguous CREATE/ADD COLUMN forms are
 * collected. A migration that merely seeds rows, drops things, or runs a DO
 * block yields nothing and is reported as UNVERIFIABLE rather than guessed at.
 */
function extractObjects(sql) {
  const s = sanitise(sql);
  const out = [];
  const seen = new Set();
  const add = (kind, ident) => {
    const key = `${kind}:${ident}`;
    if (!seen.has(key)) {
      seen.add(key);
      out.push({ kind, ident });
    }
  };

  for (const m of s.matchAll(
    /\bcreate\s+table\s+(?:if\s+not\s+exists\s+)?([\w".]+)/gi
  )) add('table', qualify(m[1]));

  // `or replace` is the common form for views and must be matched, or the
  // migration looks objectless and gets reported UNVERIFIABLE for no reason.
  for (const m of s.matchAll(
    /\bcreate\s+(?:or\s+replace\s+)?(?:materialized\s+)?view\s+(?:if\s+not\s+exists\s+)?([\w".]+)/gi
  )) add('table', qualify(m[1])); // to_regclass resolves views too

  for (const m of s.matchAll(
    /\bcreate\s+(?:unique\s+)?index\s+(?:concurrently\s+)?(?:if\s+not\s+exists\s+)?([\w".]+)/gi
  )) add('index', qualify(m[1]));

  for (const m of s.matchAll(
    /\bcreate\s+(?:or\s+replace\s+)?function\s+([\w".]+)\s*\(/gi
  )) add('function', qualify(m[1]));

  for (const m of s.matchAll(/\bcreate\s+type\s+([\w".]+)/gi))
    add('type', qualify(m[1]));

  // ALTER TABLE ... ADD COLUMN, including multiple columns in one statement.
  for (const stmt of s.split(';')) {
    const t = stmt.match(/\balter\s+table\s+(?:only\s+)?(?:if\s+exists\s+)?([\w".]+)/i);
    if (!t) continue;
    const table = qualify(t[1]);
    for (const c of stmt.matchAll(
      /\badd\s+column\s+(?:if\s+not\s+exists\s+)?([\w"]+)/gi
    )) {
      add('column', `${table}.${c[1].replace(/"/g, '').toLowerCase()}`);
    }
  }

  return out;
}

const files = readdirSync(MIGRATIONS_DIR)
  .filter((f) => f.endsWith('.sql'))
  .sort();

const rows = [];
const unverifiable = [];

for (const file of files) {
  const version = file.split('_')[0];
  const objects = extractObjects(readFileSync(join(MIGRATIONS_DIR, file), 'utf8'));
  if (objects.length === 0) {
    unverifiable.push({ version, file });
    continue;
  }
  for (const o of objects) {
    rows.push({ version, file, ...o });
  }
}

const esc = (v) => `'${String(v).replace(/'/g, "''")}'`;

const values = rows
  .map((r) => `    (${esc(r.version)}, ${esc(r.file)}, ${esc(r.kind)}, ${esc(r.ident)})`)
  .join(',\n');

console.log(`-- Migration history verification — READ ONLY.
-- Generated by scripts/verify-migration-history.mjs
--
-- Reads system catalogues only. Creates nothing, alters nothing, drops
-- nothing. Safe to run against production.
--
-- ${rows.length} objects checked across ${files.length - unverifiable.length} migrations.
--
-- Read the result as:
--   APPLIED      every object this migration creates already exists
--                → safe to mark applied with \`supabase migration repair\`
--   INCOMPLETE   some objects are missing → DO NOT mark applied; investigate
--                the \`missing\` column before doing anything

with expected(version, file, kind, ident) as (
  values
${values}
),
checked as (
  select
    e.version,
    e.file,
    e.kind,
    e.ident,
    case e.kind
      when 'table'    then to_regclass(e.ident) is not null
      when 'index'    then to_regclass(e.ident) is not null
      when 'type'     then exists (
                          select 1 from pg_type t
                          join pg_namespace n on n.oid = t.typnamespace
                          where n.nspname || '.' || t.typname = e.ident)
      when 'function' then exists (
                          select 1 from pg_proc p
                          join pg_namespace n on n.oid = p.pronamespace
                          where n.nspname || '.' || p.proname = e.ident)
      when 'column'   then exists (
                          select 1 from information_schema.columns c
                          where c.table_schema || '.' || c.table_name || '.' || c.column_name = e.ident)
      else false
    end as present
  from expected e
)
select
  version,
  min(file)                                              as file,
  count(*)                                               as objects_expected,
  count(*) filter (where present)                        as objects_found,
  case when count(*) filter (where not present) = 0
       then 'APPLIED' else 'INCOMPLETE' end              as verdict,
  coalesce(string_agg(ident, ', ') filter (where not present), '') as missing
from checked
group by version
order by version;`);

/**
 * Migrations that create no objects still leave evidence — seeded rows, a
 * policy, a rewritten constraint. Existence checking can't see those, so each
 * gets a hand-written probe. Every probe is a SELECT.
 *
 * Keyed by version so a migration that later gains a CREATE drops out of the
 * unverifiable list automatically and its probe simply stops being emitted.
 */
const SUPPLEMENTARY = {
  '20260716040000': {
    what: 'RLS policies on products + storage',
    sql: `select 'products RLS' as check, count(*)::text as value,
           case when count(*) > 0 then 'APPLIED' else 'INCOMPLETE' end as verdict
    from pg_policies where schemaname = 'public' and tablename = 'products'`,
  },
  '20260803000000': {
    what: 'lookup tables seeded',
    sql: `select 'size_master rows' as check, count(*)::text as value,
           case when count(*) > 0 then 'APPLIED' else 'INCOMPLETE' end as verdict
    from public.size_master`,
  },
  '20260803030000': {
    what: 'product v2 master data seeded',
    sql: `select 'attribute_options rows' as check, count(*)::text as value,
           case when count(*) > 0 then 'APPLIED' else 'INCOMPLETE' end as verdict
    from public.attribute_options`,
  },
  '20260810140000': {
    what: 'catalog display_order backfilled',
    sql: `select 'categories.display_order not null' as check, count(*)::text as value,
           case when count(*) > 0 then 'APPLIED' else 'INCOMPLETE' end as verdict
    from public.categories where display_order is not null`,
  },
  '20260811120000': {
    what: 'categories + colour palette seeded',
    sql: `select 'categories rows' as check, count(*)::text as value,
           case when count(*) > 0 then 'APPLIED' else 'INCOMPLETE' end as verdict
    from public.categories`,
  },
  '20260822010000': {
    what: 'orders_status check accepts lowercase',
    sql: `select 'orders status constraint' as check,
           coalesce(min(conname), 'none') as value,
           case when count(*) filter (
                  where pg_get_constraintdef(oid) like '%placed%') > 0
                then 'APPLIED' else 'INCOMPLETE' end as verdict
    from pg_constraint
    where conrelid = 'public.orders'::regclass and contype = 'c'`,
  },
};

if (unverifiable.length > 0) {
  console.log(`
-- ═══════════════════════════════════════════════════════════════════════════
-- APPENDIX — migrations with no createable objects
-- ═══════════════════════════════════════════════════════════════════════════
-- These create no table/column/index/function (data seeds, RLS policies,
-- constraint rewrites), so the query above cannot see them. Each probe below
-- looks for the EVIDENCE the migration leaves instead. Still read-only.
--
-- Run this second statement separately and read the verdict column.
`);

  const blocks = [];
  for (const u of unverifiable) {
    const probe = SUPPLEMENTARY[u.version];
    if (probe) {
      blocks.push(
        `-- ${u.version}  ${u.file}  (${probe.what})\n` +
          `select ${esc(u.version)} as version, * from (\n${probe.sql}\n) t`
      );
    } else {
      console.log(`--   ${u.version}  ${u.file}  → NO PROBE: judge by hand`);
    }
  }

  if (blocks.length > 0) {
    console.log(blocks.join('\nunion all\n') + ';');
  }
}
