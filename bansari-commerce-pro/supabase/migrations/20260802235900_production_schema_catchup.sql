  payment_gateway     text,
  payment_gateway_ref text,
  paid_at             timestamptz,

  -- shipping
  shipping_provider   text,
  tracking_number     text,
  tracking_url        text,
  shipped_at          timestamptz,
  delivered_at        timestamptz,
