do $$ begin
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='orders_v2' and policyname='orders_v2_owner_read') then
    create policy orders_v2_owner_read on public.orders_v2 for select to authenticated
      using (user_id = auth.uid());
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='orders_v2' and policyname='orders_v2_service_all') then
    create policy orders_v2_service_all on public.orders_v2 for all to service_role
      using (true) with check (true);
  end if;
end $$;

