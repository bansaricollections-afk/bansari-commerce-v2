-- SECTION 7 — INVENTORY SUMMARY VIEW
-- ============================================================

create or replace view public.inventory_summary as
select
  s.variant_id,
  l.id                                     as location_id,
  l.name                                   as location_name,
  l.code                                   as location_code,
  s.quantity,
  s.reserved,
  greatest(s.quantity - s.reserved, 0)    as available,
  s.reorder_point,
  s.reorder_qty,
  case
    when s.quantity = 0                          then 'out_of_stock'
    when s.quantity <= s.reorder_point           then 'low_stock'
    else 'in_stock'
  end                                      as stock_status,
  s.updated_at
from public.inventory_stock s
join public.inventory_locations l on l.id = s.location_id;

