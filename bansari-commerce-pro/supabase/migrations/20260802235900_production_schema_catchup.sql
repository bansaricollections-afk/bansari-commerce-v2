--   • Inventory Sprint 4 Domain
--   • Inventory Summary View
--   • product_variants compatibility columns
--
-- Safety guarantees:
--   * All CREATE TABLE        → IF NOT EXISTS
--   * All ALTER TABLE ADD COL → ADD COLUMN IF NOT EXISTS
--   * All CREATE INDEX        → IF NOT EXISTS
--   * All CREATE TYPE / enum  → DO $$ BEGIN ... EXCEPTION WHEN duplicate_object THEN NULL END $$
--   * All CREATE POLICY       → guarded by pg_policies existence check
--   * All CREATE OR REPLACE   → safe for functions/views
--   * No DROP TABLE / DROP COLUMN
--   * No data mutations
--   * Idempotent: safe to run more than once
-- ============================================================

