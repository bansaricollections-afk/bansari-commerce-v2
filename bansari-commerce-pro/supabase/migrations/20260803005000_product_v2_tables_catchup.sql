-- ============================================================
-- 2. TAGS
--    Must be created BEFORE product_tags which FKs into it.
-- ============================================================

create table if not exists public.tags (
  id            bigint generated by default as identity primary key,
  name          text    not null,
  slug          text    not null,
  active        boolean not null default true,
  display_order integer not null default 0,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint tags_name_key unique (name),
  constraint tags_slug_key unique (slug)
);

drop trigger if exists tags_set_updated_at on public.tags;
create trigger tags_set_updated_at
  before update on public.tags
  for each row execute function public.set_updated_at();

create index if not exists tags_slug_idx         on public.tags (slug);
create index if not exists tags_active_idx        on public.tags (active);
create index if not exists tags_display_order_idx on public.tags (display_order);

alter table public.tags enable row level security;

do $$ begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'tags'
      and policyname = 'tags_public_read'
  ) then
    create policy tags_public_read
      on public.tags for select using (true);
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'tags'
      and policyname = 'tags_service_all'
  ) then
    create policy tags_service_all
      on public.tags for all to service_role
      using (true) with check (true);
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'tags'
      and policyname = 'tags_admin_write'
  ) then
    create policy tags_admin_write
      on public.tags for all to authenticated
      using (
        (auth.jwt() ->> 'role') = 'admin'
        or (auth.jwt() -> 'user_metadata' ->> 'role') = 'admin'
      )
      with check (
        (auth.jwt() ->> 'role') = 'admin'
        or (auth.jwt() -> 'user_metadata' ->> 'role') = 'admin'
      );
  end if;
end $$;

