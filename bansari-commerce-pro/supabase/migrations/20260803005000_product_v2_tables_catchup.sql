-- ============================================================
-- PRODUCT V2 TABLES CATCH-UP
-- 20260803_product_v2_tables_catchup.sql
--
-- Purpose: idempotent creation / column-addition for every
--          Product V2 table that services query but that was
--          not yet applied to production because the V2
--          foundation migration was only partially applied.
--
-- Safe on:
--   * clean database        (IF NOT EXISTS everywhere)
--   * partially migrated DB (ADD COLUMN IF NOT EXISTS)
--   * current production DB (no data loss, no drops)
--
-- FK dependency order (each table created before it is referenced):
--   auth.users             — Supabase built-in, always present
--   public.products        — created by 20260702001523_initial_schema
--   public.size_master     — created by 20260802235900 catchup
--   public.tags            — created in Section 1 of THIS file
--   public.product_images  — Section 2
--   public.product_variants — Section 3
--   public.product_tags    — Section 4  (references products + tags)
--   public.product_audit_log — Section 5
-- ============================================================

-- ============================================================
-- 0. HELPER — ensure set_updated_at() exists
-- ============================================================
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

