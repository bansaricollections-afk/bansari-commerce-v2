-- 4a. Ensure the table exists (guard for clean-DB scenario)
create table if not exists public.product_variants (
  id             bigint generated by default as identity primary key,
  product_id     bigint not null references public.products (id) on delete cascade,
  sku            text   not null,
  mrp            numeric(12,2) not null default 0 check (mrp >= 0),
  selling_price  numeric(12,2) not null default 0 check (selling_price >= 0),
  stock          integer not null default 0 check (stock >= 0),
  status         text    not null default 'active',
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

-- 4b. Add V2-specific columns (all idempotent)
do $$ begin

  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'product_variants'
      and column_name = 'size_id'
  ) then
    alter table public.product_variants
      add column size_id bigint references public.size_master (id) on delete set null;
  end if;

  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'product_variants'
      and column_name = 'size_label'
  ) then
    alter table public.product_variants add column size_label text;
  end if;

  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'product_variants'
      and column_name = 'cost'
  ) then
    alter table public.product_variants
      add column cost numeric(12,2) check (cost >= 0);
  end if;

  -- V2 canonical stock column (V1 used stock_current)
  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'product_variants'
      and column_name = 'stock'
  ) then
    alter table public.product_variants
      add column stock integer not null default 0 check (stock >= 0);
  end if;

  -- V2 canonical reserved column (V1 used stock_reserved)
  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'product_variants'
      and column_name = 'reserved_stock'
  ) then
    alter table public.product_variants
      add column reserved_stock integer not null default 0 check (reserved_stock >= 0);
  end if;

  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'product_variants'
      and column_name = 'barcode'
  ) then
    alter table public.product_variants add column barcode text;
  end if;

  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'product_variants'
      and column_name = 'mrp'
  ) then
    alter table public.product_variants
      add column mrp numeric(12,2) not null default 0 check (mrp >= 0);
  end if;

  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'product_variants'
      and column_name = 'selling_price'
  ) then
    alter table public.product_variants
      add column selling_price numeric(12,2) not null default 0 check (selling_price >= 0);
  end if;

  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'product_variants'
      and column_name = 'weight_grams'
  ) then
    alter table public.product_variants
      add column weight_grams integer check (weight_grams >= 0);
  end if;

  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'product_variants'
      and column_name = 'length_cm'
  ) then
    alter table public.product_variants
      add column length_cm numeric(8,2) check (length_cm >= 0);
  end if;

  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'product_variants'
      and column_name = 'width_cm'
  ) then
    alter table public.product_variants
      add column width_cm numeric(8,2) check (width_cm >= 0);
  end if;

  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'product_variants'
      and column_name = 'height_cm'
  ) then
    alter table public.product_variants
      add column height_cm numeric(8,2) check (height_cm >= 0);
  end if;

  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'product_variants'
      and column_name = 'is_default'
  ) then
    alter table public.product_variants
      add column is_default boolean not null default false;
  end if;

  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'product_variants'
      and column_name = 'sort_order'
  ) then
    alter table public.product_variants
      add column sort_order integer not null default 0;
  end if;

  -- selling_lte_mrp constraint
  if not exists (
    select 1 from information_schema.table_constraints
    where table_schema    = 'public'
      and table_name      = 'product_variants'
      and constraint_name = 'selling_lte_mrp'
  ) then
    alter table public.product_variants
      add constraint selling_lte_mrp check (selling_price <= mrp);
  end if;

end $$;

-- Unique SKU constraint (guard for V1 tables that used a unique index instead)
do $$ begin
  if not exists (
    select 1 from information_schema.table_constraints
    where table_schema    = 'public'
      and table_name      = 'product_variants'
      and constraint_name = 'product_variants_sku_key'
      and constraint_type = 'UNIQUE'
  ) then
    -- only add if the unique index from V1 also doesn't cover it
    if not exists (
      select 1 from pg_indexes
      where schemaname = 'public'
        and tablename  = 'product_variants'
        and indexname  = 'idx_product_variants_sku'
    ) then
      alter table public.product_variants add constraint product_variants_sku_key unique (sku);
    end if;
  end if;
end $$;

