-- 4. PRODUCT VARIANTS — V2 column additions
--    The table may have been created by 20260718_inventory_v1.sql
--    with V1 column names. We ADD every V2 column that may be missing.
--    Every statement uses ADD COLUMN IF NOT EXISTS.
