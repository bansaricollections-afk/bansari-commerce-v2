-- SECTION 10 — RPC: adjust_inventory_stock
-- ============================================================

create or replace function public.adjust_inventory_stock(
  p_inventory_id bigint,
  p_qty_change   integer,
  p_reason       text,
  p_notes        text    default null,
  p_actor_id     uuid    default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_current integer;
  v_new     integer;
begin
  select available_qty into v_current
  from public.inventory
  where id = p_inventory_id
  for update;

  if not found then
    raise exception 'inventory record % not found', p_inventory_id;
  end if;

  v_new := v_current + p_qty_change;

  if v_new < 0 then
    raise exception 'insufficient stock: current=%, change=%', v_current, p_qty_change;
  end if;

  update public.inventory
  set    available_qty = v_new,
         updated_at    = now()
  where  id = p_inventory_id;

  insert into public.inventory_adjustments
    (inventory_id, qty_change, reason, notes, actor_id)
  values
    (p_inventory_id, p_qty_change,
     p_reason::public.adjustment_reason,
     p_notes, p_actor_id);

  return v_new;
end;
$$;

