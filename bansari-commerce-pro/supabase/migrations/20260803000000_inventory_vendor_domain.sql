create or replace view public.v_inventory_summary as
select
  inv.id,
  inv.warehouse_id,
  w.name                                                  as warehouse_name,
  inv.product_id,
  inv.product_name,
  inv.product_sku,
  inv.variant_id,
  inv.variant_sku,
  inv.size_label,
  inv.available_qty,
  inv.reserved_qty,
  inv.damaged_qty,
  inv.avg_cost_price,
  (inv.available_qty * inv.avg_cost_price)::numeric(14,4)  as inventory_value,
  case
    when inv.available_qty = 0                         then 'out_of_stock'
    when inv.available_qty <= inv.low_stock_threshold  then 'low_stock'
    else                                                    'in_stock'
  end::text                                               as stock_status,
  inv.low_stock_threshold
from public.inventory inv
join public.warehouses w on w.id = inv.warehouse_id;

