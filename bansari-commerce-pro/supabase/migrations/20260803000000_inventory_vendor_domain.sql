-- SECTION 12 — RPC: receive_purchase_order
-- ============================================================

create or replace function public.receive_purchase_order(
  p_po_id        bigint,
  p_receipts     jsonb,
  p_received_by  uuid
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_receipt        jsonb;
  v_item           record;
  v_warehouse_id   bigint;
  v_inv_id         bigint;
  v_new_status     public.po_status;
  v_total_ordered  integer;
  v_total_received integer;
  v_good_qty       integer;
  v_dmg_qty        integer;
  v_rcv_cost       numeric(12,4);
begin
  select warehouse_id into v_warehouse_id
  from public.purchase_orders
  where id = p_po_id
    and status not in ('received', 'cancelled')
  for update;

  if not found then
    raise exception 'purchase order % not found or not receivable', p_po_id;
  end if;

  for v_receipt in select * from jsonb_array_elements(p_receipts)
  loop
    select * into v_item
    from public.purchase_order_items
    where id    = (v_receipt->>'item_id')::bigint
      and po_id = p_po_id
    for update;

    if not found then
      raise exception 'purchase order item % not found for po %',
        v_receipt->>'item_id', p_po_id;
    end if;

    v_good_qty := (v_receipt->>'received_qty')::integer;
    v_dmg_qty  := coalesce((v_receipt->>'damaged_qty')::integer, 0);
    v_rcv_cost := coalesce((v_receipt->>'unit_cost')::numeric, v_item.unit_cost);

    update public.purchase_order_items
    set received_qty = received_qty + v_good_qty,
        damaged_qty  = damaged_qty  + v_dmg_qty,
        unit_cost    = v_rcv_cost,
        total_cost   = v_item.ordered_qty * v_rcv_cost,
        updated_at   = now()
    where id = v_item.id;

    -- Resolve inventory row
    select id into v_inv_id
    from public.inventory
    where warehouse_id = v_warehouse_id
      and product_id   = v_item.product_id
      and (variant_id  = v_item.variant_id
           or (variant_id is null and v_item.variant_id is null))
    for update;

    if found then
      update public.inventory
      set available_qty  = available_qty + v_good_qty - v_dmg_qty,
          damaged_qty    = damaged_qty   + v_dmg_qty,
          avg_cost_price = case
            when (available_qty + v_good_qty - v_dmg_qty) > 0
            then (
              (avg_cost_price * available_qty)
              + (v_rcv_cost * (v_good_qty - v_dmg_qty))
            ) / (available_qty + v_good_qty - v_dmg_qty)
            else avg_cost_price
          end,
          updated_at     = now()
      where id = v_inv_id;
    else
      insert into public.inventory
        (warehouse_id, product_id, variant_id,
         product_name, product_sku,
         available_qty, damaged_qty, avg_cost_price)
      select
        v_warehouse_id, v_item.product_id, v_item.variant_id,
        p.name,
        coalesce(pv.sku, p.sku),
        greatest(v_good_qty - v_dmg_qty, 0),
        v_dmg_qty,
        v_rcv_cost
      from public.products p
      left join public.product_variants pv on pv.id = v_item.variant_id
      where p.id = v_item.product_id
      returning id into v_inv_id;
    end if;

    insert into public.inventory_adjustments
      (inventory_id, qty_change, reason, notes, actor_id)
    values (
      v_inv_id,
      v_good_qty - v_dmg_qty,
      'vendor_credit'::public.adjustment_reason,
      coalesce(v_receipt->>'notes', 'PO receipt for po_id=' || p_po_id),
      p_received_by
    );
  end loop;

  select sum(ordered_qty), sum(received_qty)
  into v_total_ordered, v_total_received
  from public.purchase_order_items
  where po_id = p_po_id;

  v_new_status :=
    case
      when v_total_received = 0               then 'sent'
      when v_total_received >= v_total_ordered then 'received'
      else                                         'partial'
    end::public.po_status;

  update public.purchase_orders
  set status     = v_new_status,
      updated_by = p_received_by,
      updated_at = now()
  where id = p_po_id;
end;
$$;

